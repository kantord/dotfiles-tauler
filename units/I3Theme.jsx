import {
  I3Config,
  Comment,
  ClientColor,
  ClientBackground,
} from '../schemas/i3-config.schema.yaml';

// i3's own chrome — window borders and title bars — in the active tauler theme (`ctx.theme`, from
// `theme:` in the layout's frontmatter), so the window manager follows the bar.
//
// i3.config `include`s this file; it owns nothing else. A write ends with `i3-msg reload`, because
// i3 reads its colours at load, not per window. (`reload` re-reads the config in place: windows and
// layout are kept, unlike `restart`.)
//
// Which token paints which surface follows the names a UI uses: the focused window is `primary`
// with its `primary-foreground` title, an unfocused one `card` with `muted-foreground`, an urgent
// one `destructive`. A border and its title bar share a colour so the frame reads as one piece.
const I3Theme = ConfigFile({
  path: '~/.config/i3/tauler-theme.conf',
  render: () => {
    const c = ctx.theme.colors;
    const cls = (name, border, background, text, indicator) => (
      <ClientColor
        class={name}
        border={c[border]}
        background={c[background]}
        text={c[text]}
        indicator={c[indicator]}
        childBorder={c[border]}
      />
    );
    return (
      <I3Config>
        <Comment text="Generated by tauler from the active theme; edit the layout, not this file." />
        {cls('focused', 'primary', 'primary', 'primary-foreground', 'accent')}
        {cls('focused_inactive', 'border', 'secondary', 'secondary-foreground', 'border')}
        {cls('unfocused', 'border', 'card', 'muted-foreground', 'border')}
        {cls('urgent', 'destructive', 'destructive', 'destructive-foreground', 'destructive')}
        {cls('placeholder', 'border', 'card', 'muted-foreground', 'border')}
        <ClientBackground value={c.background} />
      </I3Config>
    );
  },
  apply: () => sh`i3-msg reload`,
});

export default I3Theme;
