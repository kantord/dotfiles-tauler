// GTK3's counterpart to the no-compositor rules in GtkTheme: under a window manager without a
// compositor (bare i3), the shadow GTK3 draws around client-side decorations paints as a dark
// band, so it is switched off. GTK3's colours come from its theme, which ColorScheme picks.
//
// This is the whole of `~/.config/gtk-3.0/gtk.css` — the unit owns the file.
const Gtk3Css = ConfigFile({
  path: '~/.config/gtk-3.0/gtk.css',
  render: () => `/* Generated by tauler; edit the layout, not this file. */
decoration { box-shadow: none; }
`,
});

export default Gtk3Css;
